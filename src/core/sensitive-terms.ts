/**
 * @fileoverview Words that point to a sensitive fact: a health detail, or one
 * of the special categories of personal data (religion, immigration status,
 * criminal history and so on).
 *
 * The on-device model is asked for these too, but it misses many of them, and a
 * word list never has an off day. A match is only ever FLAGGED for the user to
 * look at. It is not replaced by default, because the question being asked may
 * depend on the fact itself ("can she deduct the cost of her dialysis?").
 *
 * The lists are general vocabulary: common conditions, drug-name endings, court
 * and immigration terms. They are not tuned to any test document. Categories
 * follow HIPAA (health), GDPR Art. 9 and CCPA "sensitive personal information"
 * (the rest).
 */

/** A word or phrase that points to a sensitive fact, with its position. */
export interface TermMatch {
  start: number;
  end: number;
  kind: 'health' | 'sensitive';
  /** The category name shown to the user. */
  label: string;
  /**
   * The topic within `kind`, such as 'condition'. 'identifying' marks a
   * description that could single someone out.
   */
  topic: string;
}

interface Topic {
  kind: 'health' | 'sensitive';
  topic: string;
  label: string;
  /** Matched in any letter case. */
  words?: string[];
  /**
   * Matched exactly as written (abbreviations that are ordinary words in lower
   * case).
   */
  exact?: string[];
  /** Whole patterns, used as they are. */
  patterns?: RegExp[];
}

const HEALTH = 'Health detail';
const SENSITIVE = 'Sensitive personal detail';
const IDENTIFYING = 'Detail that could identify someone';

// A word ending like -er or -or does not establish that it describes a person
// (water, washer, filter, sensor). Use explicit human roles instead. Unknown
// roles can still be found by the model and the separate scoped-description
// checks.
const HUMAN_ROLE =
  '(?:(?:person|resident|student|member|employee|worker|owner|founder|partner|pilot|physician|nurse|doctor|surgeon|dentist|veterinarian|pharmacist|therapist|psychologist|psychiatrist|counsellor|counselor|paramedic|teacher|professor|principal|researcher|scientist|engineer|architect|technician|mechanic|electrician|plumber|carpenter|welder|farmer|baker|chef|cook|waiter|waitress|driver|operator|controller|receptionist|secretary|assistant|manager|director|officer|executive|president|mayor|sheriff|judge|lawyer|attorney|accountant|auditor|bookkeeper|clerk|firefighter|constable|deputy|detective|captain|soldier|veteran|pastor|priest|minister|rabbi|imam|monk|nun|athlete|coach|player|singer|musician|artist|actor|actress|author|writer|journalist|translator|interpreter|archaeologist|historian|librarian|survivor|witness|recipient|winner|patient|tenant|landlord|beneficiary|trustee|executor|guardian|caregiver|volunteer|applicant|candidate|competitor|consultant|specialist|economist|geologist|biologist|chemist|physicist|mathematician|statistician)s?|people|children|child|men|women|man|woman|staff|midwife|midwives)';
const ROLE_MODIFIERS =
  '(?:(?!(?:use|return|include|output|show|keep|give|write|provide|list|select|allow|and|or|with|for|in|on|from|at|of|to|by)\\b)[a-z-]+\\s){0,4}?';
const UNIQUE_PERSON = `(?:the )?(?:only|sole|last surviving|unique|first[- ]ever)\\s${ROLE_MODIFIERS}${HUMAN_ROLE}\\b`;
const uniquePerson = new RegExp(`\\b${UNIQUE_PERSON}`, 'i');
/**
 * Returns whether the text calls someone the only, sole, last surviving, unique
 * or first-ever holder of a human role ("the only pilot").
 */
export const describesUniquePerson = (text: string) => uniquePerson.test(text);
// A scoped one-of-a-kind possession can identify its owner. Requiring an asset
// noun avoids treating every "the only <thing> in <container>" as private
// context.
const UNIQUE_ASSET = `the (?:only|sole|last surviving)\\s${ROLE_MODIFIERS}(?:houses?|homes?|cabins?|cottages?|farms?|ranches?|vineyards?|orchards?|racehorses?|boats?|yachts?|schooners?|vessels?|trawlers?|aircraft|airplanes?|planes?|motorcycles?|cars?|vehicles?|business(?:es)?|companies|company|hotels?|restaurants?|shops?)`;
const SCOPED_ASSET = `${UNIQUE_ASSET} (?:in|on|at|of|for) [^.,;\\n]{2,40}?(?= and | who | that | which | but | until | since |[.,;\\n]|$)`;
const uniqueAsset = new RegExp(`\\b${SCOPED_ASSET}`, 'i');
/**
 * Returns whether the text describes a one-of-a-kind possession within a stated
 * scope ("the only vineyard in …").
 */
export const describesUniqueAsset = (text: string) => uniqueAsset.test(text);

