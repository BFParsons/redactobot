/**
 * General topic questions are not facts about a person. This never excludes
 * direct identifiers; it applies only to health/sensitive vocabulary and model
 * topic spans.
 */
export function generalTopicQuestion(
  text: string,
  start: number,
  end: number,
): boolean {
  const from =
    Math.max(
      text.lastIndexOf('\n', start - 1),
      text.lastIndexOf('. ', start - 1),
      text.lastIndexOf('? ', start - 1),
    ) + 1;
  const boundary = /[.!?](?:\s|$)|\n/g;
  boundary.lastIndex = end;
  const to = boundary.exec(text)?.index ?? text.length;
  const sentence = text.slice(from, to).trim();
  const request =
    /^(?:please\s+)?(?:explain|define|describe|compare|what (?:is|are)|how (?:does|do)|teach me about|give (?:me )?an overview of|I (?:want|need)(?: help)? (?:understanding|learning about)|I (?:have a question|am learning|am curious) about|can you (?:explain|define|describe|compare|improve my (?:essay|paper|draft) about))\b/i.test(
      sentence,
    );
  const facts = sentence
    .replace(/\bI have a question\b/gi, '')
    .replace(/\bmy (?:essay|paper|draft)\b/gi, '');
  return (
    request &&
    !/\b(?:my|our|his|her|their|patient|client|he|she|they|has|takes|taking|I have|I take|I was|diagnosed|suffers?|suffering)\b/i.test(
      facts,
    )
  );
}

/**
 * Every word or phrase in the text that points to a sensitive fact. Longest
 * match first at each place.
 */
export function sensitiveTerms(
  text: string,
  includeGeneralTopics = false,
): TermMatch[] {
  const found: TermMatch[] = [];
  for (const t of compiled) {
    for (const re of t.res) {
      for (const m of text.matchAll(re)) {
        if (m[0].length < 2 || NOT_HEALTH.test(m[0])) continue;
        if (
          t.topic === 'identifying' &&
          /^(?:the\s+)?(?:only|sole)\s+(?:use|return|include|output|show|keep|give|write|provide|list|select|allow)\b/i.test(
            m[0],
          )
        ) {
          continue;
        }
        if (
          !includeGeneralTopics &&
          t.topic !== 'identifying' &&
          generalTopicQuestion(text, m.index, m.index + m[0].length)
        ) {
          continue;
        }
        found.push({
          start: m.index,
          end: m.index + m[0].length,
          kind: t.kind,
          label: t.label,
          topic: t.topic,
        });
      }
    }
  }
  found.sort((a, b) => a.start - b.start || b.end - a.end);
  const out: TermMatch[] = [];
  let last = -1;
  for (const f of found) {
    if (f.start < last) continue;
    out.push(f);
    last = f.end;
  }
  return out;
}
