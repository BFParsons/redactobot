"""Build src/core/given-names-ssa.ts from the US Social Security Administration baby-name data.

Usage: python -I tools/build_given_names.py PATH/TO/names.zip [--min 300] [--since 1930]

Source: https://www.ssa.gov/oact/babynames/limits.html ("National data", names.zip): one file per
year, lines "Name,Sex,Count" for names given to at least 5 babies. A US Government work in the
public domain. Only names given to at least --min babies since --since are kept, lower-cased,
3+ letters, minus names already in the hand-curated GIVEN_NAMES / AMBIGUOUS_NAMES lists.
The zip is read as data only; nothing in it is executed.
"""

import collections
import io
import re
import sys
import zipfile
from pathlib import Path

args = sys.argv[1:]
if not args:
    sys.exit(__doc__)
zip_path = Path(args[0])
MIN = int(args[args.index("--min") + 1]) if "--min" in args else 300
SINCE = int(args[args.index("--since") + 1]) if "--since" in args else 1930
root = Path(__file__).resolve().parents[1]

curated = root / "src/core/given-names.ts"
existing = set(
    re.findall(
        r"[a-zà-ÿ'-]+",
        curated.read_text(encoding="utf8")
        .split("export const GIVEN_NAMES", 1)[1]
        .lower(),
    )
)

totals = collections.Counter()
with zipfile.ZipFile(zip_path) as z:
    for info in z.infolist():
        m = re.fullmatch(r"yob(\d{4})\.txt", info.filename)
        if not m or int(m.group(1)) < SINCE or info.file_size > 5_000_000:
            continue
        for line in io.TextIOWrapper(
            z.open(info), encoding="ascii", errors="ignore"
        ):
            parts = line.strip().split(",")
            if (
                len(parts) == 3
                and parts[2].isdigit()
                and re.fullmatch(r"[A-Za-z]{3,20}", parts[0])
            ):
                totals[parts[0].lower()] += int(parts[2])

names = sorted(n for n, c in totals.items() if c >= MIN and n not in existing)
out = root / "src/core/given-names-ssa.ts"
lines = [" ".join(names[i : i + 20]) for i in range(0, len(names), 20)]
out.write_text(
    "// Generated by tools/build_given_names.py from US Social Security Administration baby-name data\n"
    f"// (public domain; names given to at least {MIN} US babies since {SINCE}), minus the hand-curated lists.\n"
    "// Used only for capitalized words in mid-sentence; see discoverNames in names.ts. Do not edit by hand.\n"
    "export const SSA_GIVEN_NAMES = new Set(`\n"
    + "\n".join(lines)
    + "\n`.trim().split(/\\s+/));\n",
    encoding="utf8",
)
print(
    f"{len(names)} names written to {out.relative_to(root)} ({out.stat().st_size // 1024} KB); "
    f"{len(totals)} distinct names in the data, {len(existing)} already curated"
)
