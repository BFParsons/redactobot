/**
 * @fileoverview Explicit maintenance task only. Runtime detection never queries
 * GeoNames.
 */

import {unzipSync, strFromU8} from 'fflate';
import {createHash} from 'node:crypto';
import {writeFile, copyFile} from 'node:fs/promises';
const source = 'https://download.geonames.org/export/dump/cities15000.zip';
const response = await fetch(source);
if (!response.ok) {
  throw new Error(`GeoNames download failed: ${response.status}`);
}
const bytes = new Uint8Array(await response.arrayBuffer());
const archive = unzipSync(bytes);
const rows = strFromU8(archive['cities15000.txt']).trim().split('\n');
const names = [
  ...new Set(
    rows
      .flatMap(row => row.split('\t').slice(1, 3))
      .map(s => s.normalize('NFKC').toLowerCase())
      .filter(s => /^[\p{L}\p{M}][\p{L}\p{M} .'’-]{1,79}$/u.test(s)),
  ),
].sort();
const meta = {
  source,
  retrieved: new Date().toISOString(),
  sha256: createHash('sha256').update(bytes).digest('hex'),
  entries: rows.length,
  spellings: names.length,
  license: 'CC BY 4.0',
  scope:
    'Primary names and ASCII spellings of cities over 15,000 population or capitals. Not all places or aliases.',
};
await writeFile(
  new URL('../taxonomy/places-data.js', import.meta.url),
  '// GeoNames, CC BY 4.0. See places-data.NOTICE. Generated by tools/build_places.mjs.\n' +
    `export const PLACE_NAMES = new Set(${JSON.stringify(names.join('\n'))}.split('\\n'));\n`,
);
await writeFile(
  new URL('../taxonomy/places-data.NOTICE', import.meta.url),
  'Place names derived from GeoNames: https://www.geonames.org/\n' +
    'Licensed under Creative Commons Attribution 4.0: https://creativecommons.org/licenses/by/4.0/\n' +
    'Modified by selecting primary/ASCII names, normalizing, lowercasing and deduplicating.\n' +
    'Data provided without any guarantee of accuracy or completeness.\n\n' +
    JSON.stringify(meta, null, 2) +
    '\n',
);
await copyFile(
  new URL('../taxonomy/places-data.NOTICE', import.meta.url),
  new URL('../public/places-data.NOTICE', import.meta.url),
);
console.log(JSON.stringify(meta));
