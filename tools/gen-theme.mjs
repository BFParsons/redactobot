/**
 * @fileoverview Generates Material Design 3 colour role tokens (light + dark)
 * from one seed colour, using Google's material-color-utilities. Run: npm run
 * theme
 */

import {writeFileSync} from 'node:fs';
import {
  argbFromHex,
  hexFromArgb,
  Hct,
  SchemeTonalSpot,
  MaterialDynamicColors as C,
} from '@material/material-color-utilities';

const SEED = process.argv[2] || '#00696E';
const ROLES = [
  'primary',
  'onPrimary',
  'primaryContainer',
  'onPrimaryContainer',
  'secondary',
  'onSecondary',
  'secondaryContainer',
  'onSecondaryContainer',
  'tertiary',
  'onTertiary',
  'tertiaryContainer',
  'onTertiaryContainer',
  'error',
  'onError',
  'errorContainer',
  'onErrorContainer',
  'background',
  'onBackground',
  'surface',
  'onSurface',
  'surfaceVariant',
  'onSurfaceVariant',
  'surfaceDim',
  'surfaceBright',
  'surfaceContainerLowest',
  'surfaceContainerLow',
  'surfaceContainer',
  'surfaceContainerHigh',
  'surfaceContainerHighest',
  'outline',
  'outlineVariant',
  'inverseSurface',
  'inverseOnSurface',
  'inversePrimary',
  'surfaceTint',
  'shadow',
  'scrim',
];
const kebab = s => s.replace(/[A-Z]/g, c => '-' + c.toLowerCase());
const block = (dark, indent) => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), dark, 0);
  return ROLES.map(
    r =>
      `${indent}--md-sys-color-${kebab(r)}: ${hexFromArgb(C[r].getArgb(scheme))};`,
  ).join('\n');
};
// The system setting decides unless the user picks a theme (data-theme on
// <html>).
const css = `/*
 * Copyright 2026 The Redactobot Authors
 * SPDX-License-Identifier: Apache-2.0
 */

/* Generated by tools/gen-theme.mjs from seed ${SEED} (Material 3 tonal spot scheme). Do not edit. */
:root {
${block(false, '  ')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(true, '    ')}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${block(true, '  ')}
  color-scheme: dark;
}
`;
writeFileSync(new URL('../src/theme/tokens.css', import.meta.url), css);
console.log(`wrote src/theme/tokens.css from ${SEED}`);
